#!/usr/bin/env bash
# GoFilm LAN deployment for Linux / macOS.
#
#   ./scripts/lan/deploy-lan.sh                 # deploy + start backend on :3601
#   ./scripts/lan/deploy-lan.sh --lan-ip 192.168.1.10
#   sudo ./scripts/lan/deploy-lan.sh --install-service   # systemd unit + boot autostart
#   ./scripts/lan/deploy-lan.sh --status
#   ./scripts/lan/deploy-lan.sh --stop
#
# MySQL/Redis run in Docker and are published on 127.0.0.1 only. The backend is
# the only process that listens on the LAN (port 3601) and it keeps the media
# proxy SSRF protections in server/plugin/mediaproxy untouched.
set -euo pipefail

SERVER_PORT=3601
LAN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SELF="$LAN_DIR/$(basename "${BASH_SOURCE[0]}")"

# Two layouts are supported:
#   repository : <repo>/scripts/lan/deploy-lan.sh, build from <repo>/server
#   package    : <package>/deploy-lan.sh, use the prebuilt <package>/bin binary
if [ -f "$LAN_DIR/../../server/go.mod" ]; then
  PACKAGED=0
  ROOT="$(cd "$LAN_DIR/../.." && pwd)"
  EXE="$ROOT/dist/gofilm-lan-server"
  LOG_DIR="$ROOT/dist"
else
  PACKAGED=1
  ROOT="$LAN_DIR"
  LOG_DIR="$LAN_DIR"
  case "$(uname -m)" in
    x86_64|amd64) PKG_ARCH=amd64 ;;
    aarch64|arm64) PKG_ARCH=arm64 ;;
    *) PKG_ARCH="" ;;
  esac
  if [ -z "$PKG_ARCH" ]; then
    if [ "$(uname -s 2>/dev/null)" = "Darwin" ]; then
      echo "error: this package ships Linux binaries; on macOS deploy from the source tree instead." >&2
    else
      echo "error: unsupported CPU architecture $(uname -m); this package ships linux/amd64 and linux/arm64." >&2
    fi
    exit 1
  fi
  EXE="$ROOT/bin/gofilm-lan-server-linux-$PKG_ARCH"
fi

ENV_FILE="$LAN_DIR/.env"
COMPOSE_FILE="$LAN_DIR/docker-compose.lan.yml"
PID_FILE="$LAN_DIR/.gofilm-lan.pid"
LOG_FILE="$LOG_DIR/gofilm-lan.log"
SERVICE_NAME="gofilm-lan"
SERVICE_ENV="/etc/gofilm-lan.env"

LAN_IP=""
SKIP_BUILD=0
INSTALL_SERVICE=0
ACTION="deploy"

die() { printf 'error: %s\n' "$*" >&2; exit 1; }

case "${OSTYPE:-}" in
  msys*|cygwin*|mingw*)
    echo "note: Windows detected, scripts/lan/deploy-lan.ps1 is the supported entry point for this host." >&2
    ;;
esac

usage() { sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --lan-ip) LAN_IP="${2:-}"; [ -n "$LAN_IP" ] || die "--lan-ip needs an address"; shift 2 ;;
    --skip-build) SKIP_BUILD=1; shift ;;
    --install-service) INSTALL_SERVICE=1; shift ;;
    --stop) ACTION="stop"; shift ;;
    --status) ACTION="status"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown option: $1 (try --help)" ;;
  esac
done

rand_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 24
  else
    od -An -N24 -tx1 /dev/urandom | tr -d ' \n'
  fi
}

load_env() {
  [ -f "$ENV_FILE" ] || die "missing $ENV_FILE, run the deploy command first"
  set -a
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  set +a
}

ensure_env() {
  if [ -f "$ENV_FILE" ]; then
    load_env
  fi
  : "${LAN_MYSQL_DATABASE:=FilmSite}"
  : "${LAN_MYSQL_USER:=gofilm}"
  : "${LAN_MYSQL_PORT:=3611}"
  : "${LAN_REDIS_PORT:=3621}"
  local changed=0
  if [ -z "${LAN_MYSQL_ROOT_PASSWORD:-}" ] || [ ${#LAN_MYSQL_ROOT_PASSWORD} -lt 16 ]; then LAN_MYSQL_ROOT_PASSWORD=$(rand_hex); changed=1; fi
  if [ -z "${LAN_MYSQL_PASSWORD:-}" ] || [ ${#LAN_MYSQL_PASSWORD} -lt 16 ]; then LAN_MYSQL_PASSWORD=$(rand_hex); changed=1; fi
  if [ -z "${LAN_REDIS_PASSWORD:-}" ] || [ ${#LAN_REDIS_PASSWORD} -lt 16 ]; then LAN_REDIS_PASSWORD=$(rand_hex); changed=1; fi
  if [ -z "${GOFILM_PROXY_SECRET:-}" ] || [ ${#GOFILM_PROXY_SECRET} -lt 16 ]; then GOFILM_PROXY_SECRET=$(rand_hex); changed=1; fi
  if [ "$changed" = 1 ] || [ ! -f "$ENV_FILE" ]; then
    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by scripts/lan/deploy-lan.sh - contains secrets, do not commit.
LAN_MYSQL_DATABASE=$LAN_MYSQL_DATABASE
LAN_MYSQL_USER=$LAN_MYSQL_USER
LAN_MYSQL_PORT=$LAN_MYSQL_PORT
LAN_REDIS_PORT=$LAN_REDIS_PORT
LAN_MYSQL_ROOT_PASSWORD=$LAN_MYSQL_ROOT_PASSWORD
LAN_MYSQL_PASSWORD=$LAN_MYSQL_PASSWORD
LAN_REDIS_PASSWORD=$LAN_REDIS_PASSWORD
GOFILM_PROXY_SECRET=$GOFILM_PROXY_SECRET
EOF
    echo "Generated $ENV_FILE (random database/redis/proxy secrets)."
  fi
}

detect_ip() {
  if [ -n "$LAN_IP" ]; then echo "$LAN_IP"; return; fi
  local ip=""
  if command -v ip >/dev/null 2>&1; then
    ip=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}' || true)
  fi
  if [ -z "$ip" ] && command -v hostname >/dev/null 2>&1; then
    ip=$(hostname -I 2>/dev/null | awk '{print $1}' || true)
  fi
  if [ -z "$ip" ] && [ "$(uname -s 2>/dev/null)" = "Darwin" ]; then
    ip=$(ipconfig getifaddr en0 2>/dev/null || true)
  fi
  [ -n "$ip" ] || die "could not detect a LAN address, pass --lan-ip <address>"
  echo "$ip"
}

wait_docker() {
  local timeout="${1:-120}" waited=0
  while [ "$waited" -lt "$timeout" ]; do
    if docker info >/dev/null 2>&1; then return 0; fi
    sleep 3; waited=$((waited + 3))
  done
  die "docker is not available, start it and retry"
}

start_containers() {
  if docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" up -d --wait --wait-timeout 240 >/dev/null 2>&1; then
    return 0
  fi
  echo "compose --wait unavailable, starting containers and polling health..."
  docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" up -d
  local waited=0
  while [ "$waited" -lt 240 ]; do
    local states
    states=$(docker inspect -f '{{.State.Health.Status}}' gofilm_lan_mysql gofilm_lan_redis 2>/dev/null || true)
    if [ "$(printf '%s\n' "$states" | grep -c '^healthy$')" -eq 2 ]; then return 0; fi
    sleep 3; waited=$((waited + 3))
  done
  die "MySQL/Redis did not become healthy, check: docker logs gofilm_lan_mysql"
}

build_backend() {
  if [ "$PACKAGED" = 1 ]; then
    [ -f "$EXE" ] || die "bundled backend binary is missing: $EXE"
    chmod +x "$EXE"
    echo "Using bundled backend: $EXE"
    return 0
  fi
  mkdir -p "$(dirname "$EXE")"
  if [ "$SKIP_BUILD" = 1 ] && [ -x "$EXE" ]; then
    echo "Skipping build, using $EXE"
    return 0
  fi
  if ! command -v go >/dev/null 2>&1; then
    if [ -x "$EXE" ]; then
      echo "Go not found on PATH, reusing existing $EXE" >&2
      return 0
    fi
    die "Go toolchain not found. Install Go 1.25+ or place a server binary at $EXE"
  fi
  echo "Building backend..."
  ( cd "$ROOT/server" && go build -trimpath -ldflags "-s -w" -o "$EXE" . )
}

port_in_use() {
  if command -v ss >/dev/null 2>&1; then
    ss -ltn 2>/dev/null | awk '{print $4}' | grep -q ":$SERVER_PORT\$"
  elif command -v lsof >/dev/null 2>&1; then
    lsof -iTCP:"$SERVER_PORT" -sTCP:LISTEN -t >/dev/null 2>&1
  else
    return 1
  fi
}

backend_env() {
  printf '%s\n' \
    "MYSQL_HOST=127.0.0.1" \
    "MYSQL_PORT=$LAN_MYSQL_PORT" \
    "MYSQL_USER=$LAN_MYSQL_USER" \
    "MYSQL_PASSWORD=$LAN_MYSQL_PASSWORD" \
    "MYSQL_DBNAME=$LAN_MYSQL_DATABASE" \
    "REDIS_HOST=127.0.0.1" \
    "REDIS_PORT=$LAN_REDIS_PORT" \
    "REDIS_PASSWORD=$LAN_REDIS_PASSWORD" \
    "GOFILM_PUBLIC_BASE_URL=$BASE_URL" \
    "GOFILM_PROXY_ENABLED=true" \
    "GOFILM_PROXY_SECRET=$GOFILM_PROXY_SECRET"
}

start_backend() {
  if port_in_use; then
    echo "Port $SERVER_PORT is already in use; not starting a second backend." >&2
    return 1
  fi
  # shellcheck disable=SC2046
  nohup env $(backend_env | xargs) "$EXE" >>"$LOG_FILE" 2>&1 &
  echo $! >"$PID_FILE"
  echo "Started backend PID $(cat "$PID_FILE") (log: $LOG_FILE)"
}

install_service() {
  [ "$(id -u)" -eq 0 ] || die "--install-service requires root (use sudo)"
  backend_env > "$SERVICE_ENV"
  chmod 600 "$SERVICE_ENV"
  cat > "/etc/systemd/system/$SERVICE_NAME.service" <<EOF
[Unit]
Description=GoFilm LAN backend
After=docker.service network-online.target
Wants=network-online.target docker.service

[Service]
Type=simple
WorkingDirectory=$ROOT
EnvironmentFile=$SERVICE_ENV
ExecStartPre=/bin/sh -c "docker compose -f '$COMPOSE_FILE' --env-file '$ENV_FILE' up -d --wait"
ExecStart=$EXE
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable --now "$SERVICE_NAME"
  echo "systemd service '$SERVICE_NAME' installed and started (enabled at boot)."
}

wait_health() {
  local timeout="${1:-150}" waited=0
  local url="http://127.0.0.1:$SERVER_PORT/api/v1/health"
  while [ "$waited" -lt "$timeout" ]; do
    if command -v curl >/dev/null 2>&1; then
      curl -fsS --max-time 3 "$url" >/dev/null 2>&1 && return 0
    elif (exec 3<>"/dev/tcp/127.0.0.1/$SERVER_PORT") 2>/dev/null; then
      exec 3>&-
      return 0
    fi
    sleep 2; waited=$((waited + 2))
  done
  return 1
}

is_backend_pid() {
  local pid="$1"
  if [ -r "/proc/$pid/cmdline" ]; then
    tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null | grep -q 'gofilm-lan-server'
  else
    ps -p "$pid" -o args= 2>/dev/null | grep -q 'gofilm-lan-server'
  fi
}

stop_backend() {
  local pid=""
  if [ -f "$PID_FILE" ]; then
    pid=$(cat "$PID_FILE" 2>/dev/null || true)
    if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null && is_backend_pid "$pid"; then
      kill "$pid" 2>/dev/null || true
      for _ in 1 2 3 4 5; do kill -0 "$pid" 2>/dev/null || break; sleep 1; done
      kill -9 "$pid" 2>/dev/null || true
      echo "Stopped backend PID $pid."
    fi
    rm -f "$PID_FILE"
  fi
  if [ "$(id -u)" -eq 0 ] && command -v systemctl >/dev/null 2>&1 && [ -f "/etc/systemd/system/$SERVICE_NAME.service" ]; then
    systemctl stop "$SERVICE_NAME" 2>/dev/null || true
  fi
}

summary() {
  local healthy="$1"
  cat <<EOF

GoFilm LAN server
  LAN address : $BASE_URL
  Health      : http://127.0.0.1:$SERVER_PORT/api/v1/health  ($([ "$healthy" = 1 ] && echo OK || echo 'not responding yet'))
  MySQL/Redis : 127.0.0.1:$LAN_MYSQL_PORT / 127.0.0.1:$LAN_REDIS_PORT (loopback only)
  Secrets     : $ENV_FILE

Phone / TV app:
  On the login screen tap the server address row and enter: $BASE_URL
  The manual address switch is always available, even if the APK was built with another default.

Optional: bake the address into a build
  flutter build apk --release --dart-define=API_BASE_URL=$BASE_URL
  flutter build apk --release --dart-define=APP_TARGET=tv --dart-define=API_BASE_URL=$BASE_URL

Manage:
  $SELF --status
  $SELF --stop
  docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" logs -f

Notes:
  - the fresh LAN database starts empty and seeds the default administrator 'admin/admin'; change it after first login
  - reserve a static DHCP lease for this host so the address does not change
  - allow TCP $SERVER_PORT in the host firewall for the LAN only, e.g.:
      sudo ufw allow from 192.168.0.0/16 to any port $SERVER_PORT proto tcp
  - the backend waits ~20s for MySQL on startup, so the health check can lag
EOF
}

if [ "$ACTION" = "status" ]; then
  base_ip=$(detect_ip)
  BASE_URL="http://$base_ip:$SERVER_PORT"
  if wait_health 3; then echo "Backend: healthy  ($BASE_URL)"; else echo "Backend: down  ($BASE_URL)"; fi
  if [ -f "$ENV_FILE" ] && command -v docker >/dev/null 2>&1; then
    docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" ps || true
  fi
  exit 0
fi

if [ "$ACTION" = "stop" ]; then
  stop_backend
  if [ -f "$ENV_FILE" ] && command -v docker >/dev/null 2>&1; then
    docker compose -f "$COMPOSE_FILE" --env-file "$ENV_FILE" down
  fi
  echo "Containers stopped. Data volumes are kept (use 'down -v' to wipe)."
  exit 0
fi

wait_docker
cd "$ROOT"
ensure_env
BASE_URL="http://$(detect_ip):$SERVER_PORT"
start_containers
build_backend

if [ "$INSTALL_SERVICE" = 1 ]; then
  install_service
else
  start_backend || true
fi

if wait_health; then
  summary 1
else
  summary 0
  echo "warning: backend did not answer /api/v1/health yet, check $LOG_FILE" >&2
  exit 1
fi
