#requires -Version 5.1
<#
.SYNOPSIS
  Deploy the GoFilm backend for home / LAN use on Windows.

.DESCRIPTION
  - starts MySQL + Redis from scripts/lan/docker-compose.lan.yml (127.0.0.1 only)
  - builds dist/gofilm-lan-server.exe from server/ (unless -SkipBuild)
  - runs the backend on port 3601 with random DB/Redis passwords from scripts/lan/.env
  - advertises the detected LAN IPv4 through GOFILM_PUBLIC_BASE_URL so that
    QR login links and signed media proxy URLs work from other devices
  - optionally installs a logon scheduled task and opens the firewall port

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\lan\deploy-lan.ps1

.EXAMPLE
  .\scripts\lan\deploy-lan.ps1 -LanIp 192.168.1.10 -InstallAutostart

.EXAMPLE
  .\scripts\lan\deploy-lan.ps1 -Status
  .\scripts\lan\deploy-lan.ps1 -Stop
#>
[CmdletBinding()]
param(
    [string]$LanIp = "",
    [switch]$SkipBuild,
    [switch]$NoFirewall,
    [switch]$InstallAutostart,
    [switch]$Stop,
    [switch]$Status,
    [switch]$RunServer
)

$ErrorActionPreference = "Stop"

$ServerPort = 3601
$LanDir = $PSScriptRoot

# Two layouts are supported:
#   repository : <repo>\scripts\lan\deploy-lan.ps1, build from <repo>\server
#   package    : <package>\deploy-lan.ps1, use the prebuilt <package>\bin binary
$RepoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if (Test-Path (Join-Path $RepoRoot "server\go.mod")) {
    $Packaged = $false
    $Root = $RepoRoot
    $ExePath = Join-Path $Root "dist\gofilm-lan-server.exe"
    $LogDir = Join-Path $Root "dist"
} else {
    $Packaged = $true
    $Root = $LanDir
    $ExePath = Join-Path $LanDir "bin\gofilm-lan-server-windows-amd64.exe"
    $LogDir = $LanDir
}

$EnvFile = Join-Path $LanDir ".env"
$ComposeFile = Join-Path $LanDir "docker-compose.lan.yml"
$PidFile = Join-Path $LanDir ".gofilm-lan.pid"
$LogPath = Join-Path $LogDir "gofilm-lan.log"
$ErrLogPath = Join-Path $LogDir "gofilm-lan.err.log"
$TaskName = "GoFilmLanServer"
$FirewallRule = "GoFilm LAN $ServerPort"

function New-RandomHex {
    param([int]$Bytes = 24)
    $buf = [byte[]]::new($Bytes)
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buf) } finally { $rng.Dispose() }
    return ($buf | ForEach-Object { $_.ToString("x2") }) -join ""
}

function Read-EnvFile {
    $cfg = [ordered]@{}
    if (-not (Test-Path $EnvFile)) { return $cfg }
    foreach ($line in Get-Content -LiteralPath $EnvFile) {
        $trimmed = $line.Trim()
        if ($trimmed -eq "" -or $trimmed.StartsWith("#")) { continue }
        $idx = $trimmed.IndexOf("=")
        if ($idx -lt 1) { continue }
        $cfg[$trimmed.Substring(0, $idx)] = $trimmed.Substring($idx + 1)
    }
    return $cfg
}

function Save-EnvFile {
    param($Cfg)
    $lines = @(
        "# Generated by scripts/lan/deploy-lan.ps1 - contains secrets, do not commit."
        "LAN_MYSQL_DATABASE=$($Cfg["LAN_MYSQL_DATABASE"])"
        "LAN_MYSQL_USER=$($Cfg["LAN_MYSQL_USER"])"
        "LAN_MYSQL_PORT=$($Cfg["LAN_MYSQL_PORT"])"
        "LAN_REDIS_PORT=$($Cfg["LAN_REDIS_PORT"])"
        "LAN_MYSQL_ROOT_PASSWORD=$($Cfg["LAN_MYSQL_ROOT_PASSWORD"])"
        "LAN_MYSQL_PASSWORD=$($Cfg["LAN_MYSQL_PASSWORD"])"
        "LAN_REDIS_PASSWORD=$($Cfg["LAN_REDIS_PASSWORD"])"
        "GOFILM_PROXY_SECRET=$($Cfg["GOFILM_PROXY_SECRET"])"
    )
    Set-Content -LiteralPath $EnvFile -Value $lines -Encoding ASCII
}

function Ensure-EnvFile {
    $cfg = Read-EnvFile
    $changed = $false
    if (-not $cfg.Contains("LAN_MYSQL_DATABASE")) { $cfg["LAN_MYSQL_DATABASE"] = "FilmSite"; $changed = $true }
    if (-not $cfg.Contains("LAN_MYSQL_USER")) { $cfg["LAN_MYSQL_USER"] = "gofilm"; $changed = $true }
    if (-not $cfg.Contains("LAN_MYSQL_PORT")) { $cfg["LAN_MYSQL_PORT"] = "3611"; $changed = $true }
    if (-not $cfg.Contains("LAN_REDIS_PORT")) { $cfg["LAN_REDIS_PORT"] = "3621"; $changed = $true }
    foreach ($key in @("LAN_MYSQL_ROOT_PASSWORD", "LAN_MYSQL_PASSWORD", "LAN_REDIS_PASSWORD", "GOFILM_PROXY_SECRET")) {
        if (-not $cfg.Contains($key) -or $cfg[$key].Length -lt 16) {
            $cfg[$key] = New-RandomHex 24
            $changed = $true
        }
    }
    if ($changed -or -not (Test-Path $EnvFile)) {
        Save-EnvFile $cfg
        Write-Host "Generated $EnvFile (random database/redis/proxy secrets)."
    }
    return $cfg
}

function Get-LanAddress {
    if ($LanIp -ne "") {
        if ($LanIp -notmatch '^\d{1,3}(\.\d{1,3}){3}$') { throw "Invalid -LanIp: $LanIp" }
        return $LanIp
    }
    $preferred = Get-NetIPConfiguration |
        Where-Object { $_.NetAdapter.Status -eq "Up" -and $_.IPv4DefaultGateway -ne $null } |
        Select-Object -First 1
    if ($preferred -and $preferred.IPv4Address) { return @($preferred.IPv4Address)[0].IPAddress }
    $fallback = Get-NetIPAddress -AddressFamily IPv4 |
        Where-Object { $_.IPAddress -notmatch '^(127\.|169\.254\.)' } |
        Select-Object -First 1
    if ($fallback) { return $fallback.IPAddress }
    throw "Could not detect a LAN IPv4 address. Pass -LanIp <address>."
}

function Invoke-Native {
    param(
        [Parameter(Mandatory = $true)][string]$FilePath,
        [string[]]$Arguments = @()
    )
    # Windows PowerShell 5.1 turns native stderr into terminating errors when
    # $ErrorActionPreference is Stop, so run externals with a local Continue.
    $previous = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $output = & $FilePath @Arguments 2>&1
        $code = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $previous
    }
    return [pscustomobject]@{ Code = $code; Output = @($output) }
}

function Wait-Docker {
    param([int]$TimeoutSec = 240)
    $deadline = (Get-Date).AddSeconds($TimeoutSec)
    while ((Get-Date) -lt $deadline) {
        if ((Invoke-Native docker @("info")).Code -eq 0) { return }
        Start-Sleep -Seconds 5
    }
    throw "Docker is not running. Start Docker Desktop and run this script again."
}

function Start-Containers {
    $compose = @("compose", "-f", $ComposeFile, "--env-file", $EnvFile)
    $up = Invoke-Native docker ($compose + @("up", "-d", "--wait", "--wait-timeout", "240"))
    if ($up.Code -eq 0) { return }

    Write-Host "compose --wait unavailable, starting containers and polling health..."
    $up = Invoke-Native docker ($compose + @("up", "-d"))
    if ($up.Code -ne 0) {
        $up.Output | ForEach-Object { Write-Host $_ }
        throw "docker compose up failed."
    }

    $deadline = (Get-Date).AddMinutes(4)
    while ((Get-Date) -lt $deadline) {
        $inspect = Invoke-Native docker @("inspect", "-f", "{{.State.Health.Status}}", "gofilm_lan_mysql", "gofilm_lan_redis")
        if ($inspect.Code -eq 0 -and @($inspect.Output | Where-Object { $_ -ne "healthy" }).Count -eq 0) { return }
        Start-Sleep -Seconds 3
    }
    throw "MySQL/Redis did not become healthy in time. Check: docker logs gofilm_lan_mysql"
}

function Set-BackendEnv {
    param($Cfg, [string]$BaseUrl)
    $env:MYSQL_HOST = "127.0.0.1"
    $env:MYSQL_PORT = $Cfg["LAN_MYSQL_PORT"]
    $env:MYSQL_USER = $Cfg["LAN_MYSQL_USER"]
    $env:MYSQL_PASSWORD = $Cfg["LAN_MYSQL_PASSWORD"]
    $env:MYSQL_DBNAME = $Cfg["LAN_MYSQL_DATABASE"]
    $env:REDIS_HOST = "127.0.0.1"
    $env:REDIS_PORT = $Cfg["LAN_REDIS_PORT"]
    $env:REDIS_PASSWORD = $Cfg["LAN_REDIS_PASSWORD"]
    $env:GOFILM_PUBLIC_BASE_URL = $BaseUrl
    $env:GOFILM_PROXY_ENABLED = "true"
    $env:GOFILM_PROXY_SECRET = $Cfg["GOFILM_PROXY_SECRET"]
}

function Get-ListenerPid {
    param([int]$Port)
    $conn = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($conn) { return $conn.OwningProcess }
    return $null
}

function Wait-Health {
    param([int]$TimeoutSec = 150)
    $url = "http://127.0.0.1:$ServerPort/api/v1/health"
    $deadline = (Get-Date).AddSeconds($TimeoutSec)
    while ((Get-Date) -lt $deadline) {
        try {
            $resp = Invoke-WebRequest -UseBasicParsing -Uri $url -TimeoutSec 3
            if ($resp.StatusCode -eq 200) { return $true }
        } catch { }
        Start-Sleep -Seconds 2
    }
    return $false
}

function Build-Backend {
    if (-not (Test-Path (Split-Path $ExePath))) {
        New-Item -ItemType Directory -Force -Path (Split-Path $ExePath) | Out-Null
    }
    if ($Packaged) {
        if (-not (Test-Path $ExePath)) { throw "Bundled backend binary is missing: $ExePath" }
        Write-Host "Using bundled backend: $ExePath"
        return
    }
    if ($SkipBuild) {
        if (-not (Test-Path $ExePath)) { throw "-SkipBuild given but $ExePath does not exist." }
        Write-Host "Skipping build, using $ExePath"
        return
    }
    if (-not (Get-Command go -ErrorAction SilentlyContinue)) {
        if (Test-Path $ExePath) {
            Write-Warning "Go not found on PATH, reusing existing $ExePath"
            return
        }
        throw "Go toolchain not found. Install Go 1.25+ or build server/ elsewhere and place the binary at $ExePath."
    }
    Write-Host "Building backend..."
    Push-Location (Join-Path $Root "server")
    try {
        $build = Invoke-Native go @("build", "-trimpath", "-ldflags", "-s -w", "-o", $ExePath, ".")
        if ($build.Code -ne 0) {
            $build.Output | ForEach-Object { Write-Host $_ }
            throw "go build failed (exit $($build.Code))"
        }
    } finally {
        Pop-Location
    }
}

function Start-Backend {
    param($Cfg, [string]$BaseUrl)
    $listenerPid = Get-ListenerPid $ServerPort
    if ($listenerPid) {
        $proc = Get-Process -Id $listenerPid -ErrorAction SilentlyContinue
        $name = if ($proc) { $proc.ProcessName } else { "unknown" }
        Write-Warning "Port $ServerPort is already in use by PID $listenerPid ($name)."
        Write-Host "Stop that process first if you want this script to manage the backend."
        return $false
    }
    Set-BackendEnv $Cfg $BaseUrl
    $proc = Start-Process -FilePath $ExePath -WorkingDirectory $Root -WindowStyle Hidden `
        -RedirectStandardOutput $LogPath -RedirectStandardError $ErrLogPath -PassThru
    Set-Content -LiteralPath $PidFile -Value $proc.Id -Encoding ASCII
    Write-Host "Started backend PID $($proc.Id) (logs: $LogPath)"
    return $true
}

function Install-Autostart {
    $psExe = Join-Path $env:SystemRoot "System32\WindowsPowerShell\v1.0\powershell.exe"
    $action = "`"$psExe`" -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$PSCommandPath`" -RunServer"
    $task = Invoke-Native schtasks.exe @("/Create", "/F", "/SC", "ONLOGON", "/TN", $TaskName, "/TR", $action)
    if ($task.Code -ne 0) {
        $task.Output | ForEach-Object { Write-Host $_ }
        Write-Warning "Could not register logon task '$TaskName'. Run this script as Administrator to enable autostart."
        return
    }
    Write-Host "Autostart task '$TaskName' installed (runs at user logon)."
}

function Open-Firewall {
    if ($NoFirewall) { return }
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = [Security.Principal.WindowsPrincipal]::new($identity)
    $isAdmin = $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
    if (-not $isAdmin) {
        Write-Host "Firewall: run as Administrator, or allow manually:"
        Write-Host "  New-NetFirewallRule -DisplayName `"$FirewallRule`" -Direction Inbound -Protocol TCP -LocalPort $ServerPort -Action Allow -Profile Private,Domain"
        return
    }
    if (-not (Get-NetFirewallRule -DisplayName $FirewallRule -ErrorAction SilentlyContinue)) {
        New-NetFirewallRule -DisplayName $FirewallRule -Direction Inbound -Protocol TCP `
            -LocalPort $ServerPort -Action Allow -Profile Private,Domain | Out-Null
        Write-Host "Firewall rule '$FirewallRule' created (private/domain networks only)."
    }
}

function Stop-Backend {
    $stopped = $false
    if (Test-Path $PidFile) {
        $savedPid = 0
        $rawPid = Get-Content -LiteralPath $PidFile -Raw -ErrorAction SilentlyContinue
        if ($rawPid) { [void][int]::TryParse($rawPid.Trim(), [ref]$savedPid) }
        if ($savedPid -gt 0) {
            $proc = Get-Process -Id $savedPid -ErrorAction SilentlyContinue
            if ($proc -and $proc.ProcessName -like "gofilm-lan-server*") {
                Stop-Process -Id $savedPid -Force
                Write-Host "Stopped backend PID $savedPid."
                $stopped = $true
            }
        }
        Remove-Item -LiteralPath $PidFile -Force -ErrorAction SilentlyContinue
    }
    if (-not $stopped) {
        $portPid = Get-ListenerPid $ServerPort
        if ($portPid) {
            $proc = Get-Process -Id $portPid -ErrorAction SilentlyContinue
            if ($proc -and $proc.ProcessName -like "gofilm-lan-server*") {
                Stop-Process -Id $portPid -Force
                Write-Host "Stopped backend PID $portPid."
            } else {
                Write-Warning "Port $ServerPort is used by PID $portPid, not started by this script. Leaving it alone."
            }
        }
    }
}

function Show-Summary {
    param([string]$Address, $Cfg, [bool]$Healthy)
    Write-Host ""
    Write-Host "GoFilm LAN server"
    Write-Host "  LAN address : $Address"
    Write-Host "  Health      : http://127.0.0.1:$ServerPort/api/v1/health  ($(if ($Healthy) { 'OK' } else { 'not responding yet' }))"
    Write-Host "  MySQL/Redis : 127.0.0.1:$($Cfg["LAN_MYSQL_PORT"]) / 127.0.0.1:$($Cfg["LAN_REDIS_PORT"]) (loopback only)"
    Write-Host "  Secrets     : $EnvFile"
    Write-Host ""
    Write-Host "Phone / TV app:"
    Write-Host "  On the login screen tap the server address row and enter: $Address"
    Write-Host "  Both clients keep the manual address switch, even if the APK was built with another default."
    Write-Host ""
    Write-Host "Optional: bake the address into a build"
    Write-Host "  flutter build apk --release --dart-define=API_BASE_URL=$Address"
    Write-Host "  flutter build apk --release --dart-define=APP_TARGET=tv --dart-define=API_BASE_URL=$Address"
    Write-Host ""
    Write-Host "Manage:"
    Write-Host "  $PSCommandPath -Status"
    Write-Host "  $PSCommandPath -Stop"
    Write-Host "  docker compose -f `"$ComposeFile`" --env-file `"$EnvFile`" logs -f"
    Write-Host "Notes:"
    Write-Host "  - the fresh LAN database starts empty and seeds the default administrator 'admin/admin'; change it after first login"
    Write-Host "  - reserve a static DHCP lease for this host so the address does not change"
    Write-Host "  - allow TCP $ServerPort in the host firewall for the LAN only (Private/Domain network)"
    Write-Host "  - the backend waits ~20s for MySQL on startup, so the health check can lag"
}

# ---------------------------------------------------------------- main

if ($Status) {
    $cfg = Read-EnvFile
    $address = "http://$(Get-LanAddress):$ServerPort"
    $healthy = Wait-Health 3
    Write-Host "Backend: $(if ($healthy) { 'healthy' } else { 'down' })  ($address)"
    if ((Test-Path $ComposeFile) -and (Test-Path $EnvFile)) {
        $ps = Invoke-Native docker @("compose", "-f", $ComposeFile, "--env-file", $EnvFile, "ps")
        $ps.Output | ForEach-Object { Write-Host $_ }
    }
    exit 0
}

if ($Stop) {
    Stop-Backend
    if ((Test-Path $ComposeFile) -and (Test-Path $EnvFile)) {
        $down = Invoke-Native docker @("compose", "-f", $ComposeFile, "--env-file", $EnvFile, "down")
        $down.Output | ForEach-Object { Write-Host $_ }
    }
    Write-Host "Containers stopped. Data volumes are kept (use 'down -v' to wipe)."
    exit 0
}

Wait-Docker

$cfg = Ensure-EnvFile
$address = "http://$(Get-LanAddress):$ServerPort"

if ($RunServer) {
    # Used by the logon scheduled task: bring the stack up and run in foreground.
    Start-Containers
    if (Get-ListenerPid $ServerPort) { exit 0 }
    Set-BackendEnv $cfg $address
    Set-Location $Root
    $ErrorActionPreference = "Continue"
    & $ExePath *>> $LogPath
    exit $LASTEXITCODE
}

Start-Containers
Build-Backend
$started = Start-Backend $cfg $address
if ($InstallAutostart) { Install-Autostart }
Open-Firewall

$healthy = Wait-Health
Show-Summary -Address $address -Cfg $cfg -Healthy $healthy
if (-not $healthy -and $started) {
    Write-Warning "Backend did not answer on /api/v1/health yet. Check $LogPath"
    exit 1
}
